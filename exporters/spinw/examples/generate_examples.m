function generate_examples(output_dir)
%GENERATE_EXAMPLES Export the four periodic SpinW tutorial models.
% With SpinW and the exporter on the MATLAB path:
%   addpath('exporters/spinw/examples'); generate_examples('data/magnons');
if ~isfolder(output_dir), mkdir(output_dir); end
models = magnon_example_models;
export_magnons(fullfile(output_dir,'spinw-sw01-ferromagnetic-chain.json'), ...
    models.fm,{[0 0 0] [0.5 0 0] [1 0 0] 33}, ...
    'Name','SpinW SW01: ferromagnetic chain','Labels',{'Γ','X','Γ'},'Repetitions',[8 1 1]);
export_magnons(fullfile(output_dir,'spinw-sw02-antiferromagnetic-chain.json'), ...
    models.afm,{[0 0 0] [0.25 0 0] [0.5 0 0] 33}, ...
    'Name','SpinW SW02: antiferromagnetic chain','Labels',{'Γ','X','Γ'},'Repetitions',[4 1 1]);
export_magnons(fullfile(output_dir,'spinw-sw07-kagome.json'), ...
    models.kagome,{[-0.5 0 0] [0 0 0] [0.5 0.5 0] 33}, ...
    'Name','SpinW SW07: kagome antiferromagnet','Labels',{'M','Γ','M′'},'Repetitions',[3 3 1]);
export_magnons(fullfile(output_dir,'spinw-sw12-triangular-easy-plane.json'), ...
    models.triangular,{[0 0 0] [1/3 1/3 0] [2/3 2/3 0] 25}, ...
    'Name','SpinW SW12: triangular easy plane (3×3 magnetic cell)', ...
    'Labels',{'Γ','K','K′'},'Repetitions',[2 2 1]);
end
